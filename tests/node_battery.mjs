// Ejecuta funciones puras de scripts/*.mjs sobre las entradas que manda la prueba (stdin JSON) y devuelve los resultados.
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const ROOT = process.argv[2];
const imp = (m) => import(pathToFileURL(path.join(ROOT, 'scripts', m)).href);
const T = await imp('time.mjs');
const S = await imp('stats.mjs');
const W = await imp('weekly.mjs');
const C = await imp('challenges.mjs');
const E = await imp('events.mjs');
const D = await imp('duos.mjs');
const F = await imp('flex.mjs');
const R = await imp('riot.mjs');
const input = JSON.parse(readFileSync(0, 'utf8'));
const out = {};
out.time = input.times.map((t) => [T.madridParts(t), T.dayStart(t), T.weekStart(t), T.monthStart(t), T.weekKey(t), T.shortDay(t), T.rangeLabel(t, t + 6 * 864e5)]);
out.days = input.days.map((d) => T.parseDay(d));
out.stats = input.histories.map((h) => S.computeAccountStats(h));
out.weeks = input.weeks.map(([from, to]) => { const w = W.computeWeek(input.entries, from, to); return [w, W.compactWeek(w), to ? W.weekEmbed(w) : null]; });
out.challenges = input.chNows.map((now) => { const cs = C.computeChallenges(input.chDefs, { players: input.entries }, now);
  return [cs, cs.map((c) => [C.challengeStatus(input.chDefs.find((d) => d.id === c.id), now), C.challengeEmbed(C.challengeEvent(c, 'start', now)), C.challengeEmbed(C.challengeEvent(c, 'end', now))])]; });
out.events = input.eventPairs.map(([prev, next, ctx]) => E.detectEvents(prev, next, { now: ctx.now, newGames: new Map(Object.entries(ctx.newGames)), peakBefore: new Map(Object.entries(ctx.peakBefore)) }));
out.embeds = input.logEvents.map((e) => [E.eventText(e), E.eventEmbed(e, { ddVersion: '15.22.1' })]);
out.scoreLabels = input.scores.map((s) => E.scoreLabel(s));
out.duos = D.computeDuos(input.duoEntries.map((e) => ({ ...e, lpMap: new Map(Object.entries(e.lpMap)) })));
out.flex = F.flexGroupStats(input.flexEntries);
out.matches = input.matches.map(([m, puuid, tl]) => [R.compactMatch(m, puuid, input.dd, tl), R.matchDetail(m, input.dd)]);
out.parseRank = input.ranks.map((r) => C.parseRank(r));
process.stdout.write(JSON.stringify(out));
